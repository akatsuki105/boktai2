// ベクトル (x, y) の向きを角度 (0〜255) で返す (atan2)
s32 ArcTan2_8(s32 x, s32 y) {
  if (x == 0) {
    if (y == 0) {
      return 0;
    }
    if (y > 0) {
      return 0x40;
    }
    return 0xC0;
  }
  if (y == 0) {
    if (x > 0) {
      return 0;
    }
    return 0x80;
  }
  if (x > 0) {
    if (y > 0) {
      if (x > y) {
        return gArctanTable[Div(y * 256, x)];
      }
      return 0x40 - gArctanTable[Div(x * 256, y)];
    }
    if (x > -y) {
      return (0x100 - gArctanTable[Div(y * -256, x)]) & 0xFF;
    }
    return gArctanTable[Div(x * 256, -y)] + 0xC0;
  }
  if (y > 0) {
    if (-x > y) {
      return 0x80 - gArctanTable[Div(y * 256, -x)];
    }
    return gArctanTable[-Div(x * 256, y)] + 0x40;
  }
  if (-x > -y) {
    return gArctanTable[-Div(y * 256, -x)] + 0x80;
  }
  return 0xC0 - gArctanTable[-Div(x * 256, -y)];
}

// 座標 a から b へ t / (1 << shift) の割合で線形補間する (負の値も 0 方向に丸める)
void LerpVec3(Vec3* dst, Vec3* a, Vec3* b, s32 t, s32 shift) {
  s32 k, v;

  k = (1 << shift) - t;
  v = a->x * k + b->x * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->x = v;
  v = a->y * k + b->y * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->y = v;
  v = a->z * k + b->z * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->z = v;
}

