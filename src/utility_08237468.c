// パレット16色を src1 から src2 へ t / (1 << shift) の割合で混ぜて dst に書き出す
void BlendPltt(rgb555* dst, rgb555* src1, rgb555* src2, s32 t, s32 shift) {
  s32 r, g, b;
  s32 i;

  for (i = 0; i < 16; i++) {
    r = ((*src1 & (0x1F << 0)) * ((1 << shift) - t) + (*src2 & (0x1F << 0)) * t) >> shift;
    g = ((*src1 & (0x1F << 5)) * ((1 << shift) - t) + (*src2 & (0x1F << 5)) * t) >> shift;
    b = ((*src1 & (0x1F << 10)) * ((1 << shift) - t) + (*src2 & (0x1F << 10)) * t) >> shift;
    *dst = (r & (0x1F << 0)) | (g & (0x1F << 5)) | (b & (0x1F << 10));
    src1++;
    src2++;
    dst++;
  }
}

// パレット16色を指定色へ t / (1 << shift) の割合で近づけて dst に書き出す
void BlendPlttToColor(rgb555* dst, rgb555* src, rgb555 color, s32 t, s32 shift) {
  s32 r1, g1, b1, r2, g2, b2;
  s32 i;

  r2 = color & (0x1F << 0);
  g2 = color & (0x1F << 5);
  b2 = color & (0x1F << 10);
  for (i = 0; i < 16; i++) {
    r1 = ((*src & (0x1F << 0)) * ((1 << shift) - t) + r2 * t) >> shift;
    g1 = ((*src & (0x1F << 5)) * ((1 << shift) - t) + g2 * t) >> shift;
    b1 = ((*src & (0x1F << 10)) * ((1 << shift) - t) + b2 * t) >> shift;
    *dst = (r1 & (0x1F << 0)) | (g1 & (0x1F << 5)) | (b1 & (0x1F << 10));
    src++;
    dst++;
  }
}

// 経過時間 t に応じて点滅 (bit0) を速めていき、60 を超えたら点灯したまま TRUE を返す
