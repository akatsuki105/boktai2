// 文字列を固定長 (length 文字 + 終端) のバッファにコピーし、余りを 0 で埋める
u32 StrCopyPadded(u8* src, u8* dst, s32 length) {
  s32 i;

  for (i = 0; i < length && *src != 0; i++) {
    *dst++ = *src++;
  }
  for (; i < length + 1; i++) {
    *dst++ = 0;
  }
  return 0;
}

