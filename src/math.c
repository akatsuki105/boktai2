// 座標 a から b へ t / (1 << shift) の割合で線形補間する (負の値も 0 方向に丸める)
void LerpVec3(Vec3* dst, Vec3* a, Vec3* b, s32 t, s32 shift) {
  s32 k, v;

  k = (1 << shift) - t;
  v = a->x * k + b->x * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->x = v;
  v = a->y * k + b->y * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->y = v;
  v = a->z * k + b->z * t;
  if (v >= 0) {
    v >>= shift;
  } else {
    v = -(-v >> shift);
  }
  dst->z = v;
}
