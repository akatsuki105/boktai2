#!/usr/bin/env -S deno run --allow-read --allow-run --allow-write

import { Command } from "@cliffy/command";
import * as gba from "../common/gba/gba.ts";
import type { addr } from "../common/gba/gba.ts";
import * as path from "@std/path";
import * as MFT from "../encoding/mft/mft.ts";
import * as GAS from "../encoding/gas/gas.ts";
import * as Tilemap from "../encoding/tilemap/tilemap.ts";

const filename = path.basename(import.meta.filename ?? "unknown.ts");
const indent = "  ";

const ID = 0xE53E;

// Boktai2 のタイルマップをすべて .bin ファイルとしてダンプする
// ここの .bin ファイルは dumpFile で .s 形式に変換できる
const dumpDir = new Command()
  .argument("<rom:string>", "Path to a GBA ROM file.")
  .argument("<output:string>", "Tilemap output directory.") // .bin の出力先
  .option("-d, --dry-run", "stdout only, do not write files.")
  .action((opts, romPath, outDir) => {
    const rom = new DataView((Deno.readFileSync(romPath)).buffer);
    const hdr = MFT.getFSEntry(rom, ID);
    if (hdr.end == null) throw new Error("Invalid MFT header: end is null");
    const dir = MFT.ParseDirectory(rom, hdr.ptr);

    console.log(`@ Generated by tools/dumper/${filename}\n@ Do not edit this file manually.\n`);
    console.log(GAS.IncludeMacro + "\n");
    console.log(GAS.Align4);
    console.log(GAS.Rodata + "\n");

    console.log(GAS.dumpGlobalSymbol("gTilemapDirectory") + ` @ 0x${gba.toHex32(dir.addr)}`);
    console.log(MFT.StringifyDirectory(dir, indent));
    console.log(`@ Files`);

    if (!opts.dryRun) {
      Deno.mkdirSync(outDir, { recursive: true });
    }

    for (let i = 0; i < dir.entryNum; i++) {
      const start: addr = dir.addr + dir.fileOffsets[i];
      const end: addr = ((i + 1) < dir.entryNum) ? dir.addr + dir.fileOffsets[i + 1] : hdr.end;
      const magic = gba.getU32(rom, start);

      let data = new Uint8Array<ArrayBufferLike>(rom.buffer, start - gba.BASE, end - start);
      const isCompressed = magic !== Tilemap.MAGIC; // LZ77 compressed
      if (isCompressed) {
        const decompressedSize = gba.getU32(rom, start) >> 8;
        data = gba.decompressLZ77(data);
        if (data.length !== decompressedSize) {
          throw new Error(`Decompressed size mismatch: expected ${decompressedSize}, got ${data.length}`);
        }
      }

      const fileID = dir.ids[i];
      const filename = `${gba.toHex16(fileID)}.bin`;
      const filePath = path.join(outDir, filename);
      if (!opts.dryRun) {
        Deno.writeFileSync(filePath, data);
      }

      console.log(`Tilemap_${gba.toHex16(fileID)}:` + ` @ 0x${gba.toHex32(start)}, index: ${i}`);
      const incbinPath = `${filePath}${isCompressed ? ".lz" : ""}`;
      const output = `.incbin "${incbinPath}"`;
      console.log(indent + output);
    }
  });

// dumpDir を 終えた後、 個別の Tilemap ファイルを .s 形式で出力するためのコマンド
// ビルドするときは
//   arm-none-eabi-as -o file.o file.asm
//   arm-none-eabi-objcopy -O binary file.o file.bin
// タイルセットを持つ Tilemap ファイルの場合、 tiles.4bpp も必要になる
// e.g. ./tools/dumper/tilemap.ts file data/tilemap/0101.bin > tmp/0101.asm
const dumpFile = new Command()
  .argument("<path:string>", "Path to a Tilemap bin data") // e.g. data/tilemap/0012.bin
  .action((opts, datapath) => {
    const data = Deno.readFileSync(datapath);
    let offset = 0;
    let ok = Tilemap.CheckMagic(data, offset);
    if (!ok) {
      // u32
      const compressionMetadata = new DataView(data.buffer, offset, 4).getUint32(0, true);
      offset += 4; // Skip compression metadata
      ok = Tilemap.CheckMagic(data, offset);
      if (ok) {
        console.log(`.4byte 0x${compressionMetadata.toString(16).toUpperCase().padStart(8, "0")} @ Compression Metadata\n`);
      }
    }
    if (!ok) {
      console.error("Invalid Tilemap file");
      Deno.exit(1);
    }

    console.log(Tilemap.Macros);

    console.log("Header:");
    const id = path.basename(datapath, path.extname(datapath)); // e.g. 0012
    const f = Tilemap.ParseFile(new Uint8Array(data.buffer, offset));
    console.log(Tilemap.StringifyFileHeaderAsm(f.header).join("\n"));

    const hasTileset = f.tiles != null;
    console.log(`Tileset: @ u8[${hasTileset ? f.tiles!.byteLength : 0}]`);
    if (hasTileset) console.log(`  .incbin "tiles.4bpp"`);

    console.log(`Metatiles: @ u16[${f.metatiles.length >> 2} * 4]`);
    for (let i = 0; i < f.metatiles.length >> 2; i++) {
      // u16 x 4
      let line = "";
      for (let j = 0; j < 4; j++) {
        line += `0x${f.metatiles[(i << 2) + j].toString(16).toUpperCase().padStart(4, "0")}, `;
      }
      console.log(`  .2byte ${line.slice(0, -2)} @ ${i}`);
    }

    // console.log(`MetatileMaps: @ u16[${f.mtmap.length}]`);
    for (let i = 0; i < f.mtmap.length >> 4; i++) {
      if (i % 16 === 0) console.log(`MetatileMap${i >> 4}:`);
      let line = "";
      for (let j = 0; j < 16; j++) {
        line += `${f.mtmap[(i << 4) + j].toString(10).padStart(5, " ")},`;
      }
      console.log(`  .2byte ${line.slice(0, -1)}`);
    }
  });

// ./tools/dumper/tilemap.ts ./baserom.gba tmp/tilemap -d
const main = () => {
  new Command()
    .name("tilemap.ts")
    .description("Dump Boktai2 Tilemaps")
    .command("dir", dumpDir)
    .command("file", dumpFile)
    .parse(Deno.args);
};

if (import.meta.main) main();
