#!/usr/bin/env -S deno run --allow-read

import { Command } from "@cliffy/command";
import * as gba from "../common/gba/gba.ts";
import type { addr } from "../common/gba/gba.ts";
import * as path from "@std/path";
import * as MFT from "../encoding/mft/mft.ts";
import * as GAS from "../encoding/gas/gas.ts";
import * as ANIM from "../encoding/animation.ts";

const filename = path.basename(import.meta.filename ?? "unknown.ts");
const indent = "  ";

const ID = 0x5130;

const macros = `
.macro animation variant_count, cmd_idx, cmd_count
  .byte \\variant_count, \\cmd_count
  .2byte 4 + (ANIM_COUNT << 2) + (\\cmd_idx << 1)
.endm

.macro animcmd spriteidx, duration, xflip=0, yflip=0
  .2byte ((\\spriteidx << 6) | (\\yflip << 5) | (\\xflip << 4) | \\duration)
.endm

.macro animcmd_end
  .4byte 0x0
.endm
`;

const stringifyFile = (rom: DataView, hdr: MFT.FSEntry, dir: MFT.Directory, idx: number) => {
  const start: addr = dir.addr + dir.fileOffsets[idx];
  const end: addr = ((idx + 1) < dir.entryNum) ? dir.addr + dir.fileOffsets[idx + 1] : hdr.end!;
  const data = new Uint8Array<ArrayBufferLike>(rom.buffer, start - gba.BASE, end - start);
  const f = ANIM.Parse(data);

  const fileID = dir.ids[idx];
  console.log(`Animation_${gba.toHex16(fileID)}: @ 0x${gba.toHex32(start)}, index: ${idx}`);
  console.log(ANIM.Stringify(f, indent) + "\n");
};

// ./tools/dumper/animation.ts all baserom.gba
const allCmd = new Command()
  .description("Dump all animation data from the ROM.")
  .argument("<rom:string>", "Path to a GBA ROM file.")
  .action((opts, romPath) => {
    const rom = new DataView((Deno.readFileSync(romPath)).buffer);
    const hdr = MFT.getFSEntry(rom, ID);
    if (hdr.end == null) throw new Error("Invalid MFT header: end is null");
    const dir = MFT.ParseDirectory(rom, hdr.ptr);

    console.log(`@ Generated by tools/dumper/${filename}\n@ Do not edit this file manually.\n`);
    console.log(GAS.IncludeMacro);
    console.log(GAS.Align4);
    console.log(GAS.Rodata);
    console.log(macros);

    console.log(GAS.dumpGlobalSymbol("gAnimDirectory") + ` @ 0x${gba.toHex32(dir.addr)}`);
    console.log(MFT.StringifyDirectory(dir, indent));
    console.log(`@ Files`);

    for (let i = 0; i < dir.entryNum; i++) {
      console.log(GAS.Align4);
      stringifyFile(rom, hdr, dir, i);
    }
  });

// ./tools/dumper/animation.ts file baserom.gba 0xA929
const fileCmd = new Command()
  .argument("<rom:string>", "Path to a GBA ROM file.")
  .argument("<fileID:number>", "ID of the anim file to dump.")
  .action((_, romPath, targetID) => {
    const rom = new DataView((Deno.readFileSync(romPath)).buffer);
    const hdr = MFT.getFSEntry(rom, ID);
    if (hdr.end == null) throw new Error("Invalid MFT header: end is null");
    const dir = MFT.ParseDirectory(rom, hdr.ptr);
    const fileIndex = dir.ids.indexOf(targetID);
    if (fileIndex === -1) throw new Error(`File ID ${targetID} not found in the directory`);
    stringifyFile(rom, hdr, dir, fileIndex);
  });

const main = () => {
  new Command()
    .name("animation.ts")
    .command("all", allCmd) // ディレクトリ + ファイル全部
    .command("file", fileCmd) // 指定したファイルIDのアニメーションをダンプ
    .parse(Deno.args);
};

if (import.meta.main) main();
