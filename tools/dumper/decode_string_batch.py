def main() -> None:
    if len(sys.argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        sys.exit(1)

    start_id = int(sys.argv[1])
    end_id = int(sys.argv[2]) if len(sys.argv) == 3 else start_id + 1

    if not (0 <= start_id <= end_id <= len(STRING_ADDRS)):
        print(
            f"error: ID範囲が不正です (0 <= start <= end <= {len(STRING_ADDRS)} である必要があります)",
            file=sys.stderr,
        )
        sys.exit(1)

    char_map, escape_map, constant_map = ds.parse_charmap(ds.CHARMAP_PATH)
    term_seq = ds.find_terminator_seq(char_map)
    rom_data = ROM_PATH.read_bytes()

    for idx in range(start_id, end_id):
        addr = STRING_ADDRS[idx]
        offset = addr - ds.ROM_BASE
        window = rom_data[offset : offset + ds.READ_WINDOW]

        body = ds.decode(window, char_map, escape_map, constant_map)
        if body is not None:
            print(f"String_{idx:04X}:: @ 0x{addr:08X}, ID: {idx}")
            print(f'  .string "{body}"')
            continue

        end = window.find(term_seq)
        if end == -1:
            print(
                f"@ Binary_{idx:04X} @ 0x{addr:08X}, ID: {idx}: "
                f"終端が見つからないためスキップ",
                file=sys.stderr,
            )
            continue

        raw = window[: end + len(term_seq)]
        print(f"Binary_{idx:04X}:: @ 0x{addr:08X}, ID: {idx}")
        print(ds.format_byte_dump(raw))


if __name__ == "__main__":
    main()
