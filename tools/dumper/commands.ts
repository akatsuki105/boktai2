#!/usr/bin/env -S deno run --allow-read

import { Command } from "@cliffy/command";
import * as path from "@std/path";

// src/vm_commands.s の gCommandList から、コマンドIDに名前を付けるヘッダを作って標準出力に書き出す。
// .bokc の Command / Chara の第1引数をマクロ名で書くためのもので、.bokc からしか include しない。
//
// e.g. commands.ts src/vm_commands.s > data/scripts/commands.h
//   `.4byte 0x0074, Dvalinn_Create` -> `#define Dvalinn_Create 0x0074`

const filename = path.basename(import.meta.filename ?? "unknown.ts");

const TABLE_LABEL = "gCommandList:";
const ENTRY = /^\s*\.4byte\s+0x([0-9A-Fa-f]+)\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\b/;
const TERMINATOR = /^\s*\.4byte\s+0x0+\s*,\s*0x0+\b/;

type Entry = { id: number; name: string };

// gCommandList のラベルから終端 (.4byte 0x0000, 0x00000000) までを読む。表の中に読めない .4byte があればエラーにする。
const parseCommandList = (src: string): Entry[] => {
  const lines = src.split("\n");
  const start = lines.findIndex((l) => l.trimStart().startsWith(TABLE_LABEL));
  if (start < 0) throw new Error(`${TABLE_LABEL} が見つかりません`);

  const entries: Entry[] = [];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (TERMINATOR.test(line)) return entries;
    if (!/^\s*\.4byte\b/.test(line)) continue; // 空行やコメント
    const m = ENTRY.exec(line);
    if (m === null) throw new Error(`${i + 1}行目を読めません: ${line.trim()}`);
    entries.push({ id: parseInt(m[1], 16), name: m[2] });
  }
  throw new Error("gCommandList の終端 (.4byte 0x0000, 0x00000000) が見つかりません");
};

const render = (entries: Entry[]): string => {
  const out: string[] = [];
  out.push(`// Generated by tools/dumper/${filename}`);
  out.push("// Do not edit this file manually.");
  out.push("");
  out.push("#ifndef __DATA_SCRIPTS_COMMANDS_H__");
  out.push("#define __DATA_SCRIPTS_COMMANDS_H__");
  out.push("");
  out.push("// data/scripts/scripts.bokc で include する用");
  out.push("");
  for (const e of entries) {
    out.push(`#define ${e.name} 0x${e.id.toString(16).toUpperCase().padStart(4, "0")}`);
  }
  out.push("");
  out.push("#endif // __DATA_SCRIPTS_COMMANDS_H__");
  return out.join("\n");
};

const main = () => {
  new Command()
    .name(filename)
    .description("src/vm_commands.s の gCommandList から、コマンドIDの名前を定義したヘッダを標準出力に書き出す。")
    .argument("<input:string>", "src/vm_commands.s")
    .action((_, inputPath) => {
      try {
        const entries = parseCommandList(Deno.readTextFileSync(inputPath));

        // 同じ名前が2回出ると #define が衝突する
        const seen = new Map<string, number>();
        for (const e of entries) {
          const prev = seen.get(e.name);
          if (prev !== undefined) throw new Error(`${e.name} が 0x${prev.toString(16)} と 0x${e.id.toString(16)} の2つのIDに使われています`);
          seen.set(e.name, e.id);
        }

        console.log(render(entries));
      } catch (e) {
        console.error(e instanceof Error ? e.message : String(e));
        Deno.exit(1);
      }
    })
    .parse(Deno.args);
};

if (import.meta.main) main();
